IK_DAMPING = 1e-3
IK_STEP_SIZE = 0.6
IK_ITERS_PER_FRAME = 24

RED_BODY = "red_cube"
BLUE_BODY = "blue_cube"

# Module-level aliases, rebound by set_active_robot() so
# `import pick_place_common as task; task.TABLE_CENTER` sees the selected robot.
# Do NOT `from pick_place_common import TABLE_CENTER` before resolving the scene.
_active: RobotSpec | None = None
CUBE_HALF = 0.022
TABLE_CENTER = np.zeros(3)
TABLE_HALF_SIZE = np.zeros(3)
RED_CUBE_POS = np.zeros(3)
BLUE_CUBE_POS = np.zeros(3)
STACK_ON_BLUE_Z = 0.0
GRIPPER_OPEN = 0.0
GRIPPER_CLOSED = 0.0
SEED_POSE = np.zeros(6)
HOME_CTRL = np.zeros(6)


def active_robot() -> RobotSpec:
    return _active or get_robot()


def set_active_robot(spec: RobotSpec) -> RobotSpec:
    """Bind layout constants to *spec* so `task.TABLE_CENTER` etc. stay in sync."""
    global _active, CUBE_HALF, TABLE_CENTER, TABLE_HALF_SIZE
    global RED_CUBE_POS, BLUE_CUBE_POS, STACK_ON_BLUE_Z
    global GRIPPER_OPEN, GRIPPER_CLOSED, SEED_POSE, HOME_CTRL
    _active = spec
    CUBE_HALF = spec.cube_half
    TABLE_CENTER = spec.table_center
    TABLE_HALF_SIZE = spec.table_half_size
    RED_CUBE_POS = spec.red_cube_pos
    BLUE_CUBE_POS = spec.blue_cube_pos
    STACK_ON_BLUE_Z = spec.stack_on_blue_z
    GRIPPER_OPEN = spec.gripper_open
    GRIPPER_CLOSED = spec.gripper_closed
    SEED_POSE = spec.home_ctrl.copy()
    HOME_CTRL = spec.home_ctrl.copy()
    return spec


