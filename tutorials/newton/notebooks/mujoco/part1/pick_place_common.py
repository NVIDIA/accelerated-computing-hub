# ============================================================================
#  Shared task logic — used by every part of this series
# ============================================================================
#
#  This module is the brain of the pick-and-place task. Every part of the
#  series imports it unchanged, so the *task* stays identical and the only
#  thing that varies is the physics backend you are learning about:
#
#      Article 2 / Part 1   so101_pick_place.py  ->  mujoco.mj_step      (CPU)
#      Article 2 / Part 2   so101_mjwarp.py      ->  mujoco_warp.step    (GPU)
#      Article 3 / Part 3   so101_newton.py      ->  SolverMuJoCo.step() (Newton)
#
#  The same code drives two robots, selected with --robot:
#
#      so101   Robot Studio SO-101 (5-DoF + hinge gripper)
#      rebot   Seeed reBot DevArm  (6-DoF + coupled slide gripper)
#              https://github.com/google-deepmind/mujoco_menagerie/tree/main/seeed_rebot_devarm
#
#  You are NOT asked to modify this file during the exercises.
#
#  Anatomy of the task
#  -------------------
#    1. Scene .............. robot MJCF from Menagerie + a table + two cubes
#    2. Inverse kinematics . damped least squares on the jaw aperture center,
#                           using only stock MuJoCo (mj_jac)
#    3. Controller ......... a small state machine that interpolates between
#                           Cartesian waypoints and ramps the gripper
#    4. Grasp .............. a *real* friction grasp: the jaws close on the
#                           cube's side faces and lift it
#
#  Two lessons that cost real debugging time:
#    * Drive IK to the measured aperture center, not an end-effector site.
#    * Close the gripper gradually. Slamming the jaw shoves the cube away.

